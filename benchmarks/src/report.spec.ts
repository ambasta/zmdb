import { describe, it, expect } from 'vitest';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { runValidationSuite, zmdbAdapter } from './validation/adapter.ts';
import { seed, runOrmSuite, competitorDnf, type OrmEngine } from './orm/adapter.ts';
import { validateResult, type BenchResult } from './results.ts';

// Generates benchmarks/RESULTS.md from live runs (validation + ORM against
// node:sqlite). Competitor rows are honest DNF. This doubles as a test that the
// full report is schema-valid and deterministically ordered.

function generate(): BenchResult[] {
  const desc = {
    kind: 'object' as const,
    fields: { id: { kind: 'number' as const, minimum: 0 }, email: { kind: 'string' as const } },
  };
  const valid = runValidationSuite('zmdb', zmdbAdapter, desc, { id: 1, email: 'a@b.com' }, 500);

  const db = new DatabaseSync(':memory:');
  const engine: OrmEngine = {
    exec: (s) => db.exec(s),
    all: (s, p) => db.prepare(s).all(...(p as unknown[])) as Record<string, unknown>[],
  };
  seed(engine, 50, 4);
  const orm = [...runOrmSuite(engine, 200), ...competitorDnf()];
  return [...valid, ...orm];
}

function toMarkdown(all: BenchResult[]): string {
  const fmt = (r: BenchResult) =>
    `| ${r.suite} | ${r.case} | ${r.target} | ${r.status === 'ok' ? `${r.opsPerSec} ops/s` : r.dnfReason} |`;
  const sorted = [...all].sort((a, b) =>
    (a.suite + a.case + a.target).localeCompare(b.suite + b.case + b.target),
  );
  return [
    '# Benchmark Results',
    '',
    '> Generated by `benchmarks/src/report.spec.ts`. Validation + ORM suites run',
    '> in-process (ORM against Node 26 `node:sqlite`). Live-PostgreSQL competitor',
    '> rows are honest `DNF (not implemented)`; anti-pattern rows are',
    '> `DNF (anti-pattern)`. Numbers are indicative of the harness on the machine',
    '> that generated them, not an official ranking.',
    '',
    '| Suite | Case | Target | Result |',
    '|-------|------|--------|--------|',
    ...sorted.map(fmt),
    '',
  ].join('\n');
}

describe('benchmark report generation', () => {
  it('produces a schema-valid, deterministically-ordered RESULTS.md', () => {
    const all = generate();
    for (const r of all) expect(validateResult(r)).toEqual([]);

    const md = toMarkdown(all);
    // Deterministic ordering: regenerating yields the same body (numbers aside).
    const shape = (s: string) => s.replace(/\d+ ops\/s/g, 'N ops/s');
    expect(shape(toMarkdown(generate()))).toBe(shape(md));

    const here = dirname(fileURLToPath(import.meta.url));
    writeFileSync(join(here, '..', 'RESULTS.md'), md);
    expect(md).toContain('dnf (anti-pattern)');
    expect(md).toContain('dnf (not implemented)');
  });
});
