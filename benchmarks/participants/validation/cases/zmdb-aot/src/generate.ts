// Generates the zmdb-aot validators for this suite by running the REAL
// @zmdb/aot-validator transform over `is<T>()` source — so the benchmarked code
// is transformer output, not a hand-tuned lookalike. Bundled to CJS and executed
// by the `compile:zmdb-aot` script, which passes the output path as argv[2]
// (the bundle is CJS, so there is no import.meta.url to resolve against).
//
// Relative depth: this file lives at
//   benchmarks/upstream/typescript-runtime-type-benchmarks/cases/zmdb-aot/src
// so six levels up is the repository root.
import { writeFileSync } from 'node:fs';

import { transformTypeChecks } from '../../../../../../packages/aot-validator/src/plugin/index.ts';

// The suite's data model, written as the type literal the transformer inlines.
const MODEL = [
  '{ number: number; negNumber: number; maxNumber: number; string: string;',
  ' longString: string; boolean: boolean;',
  ' deeplyNested: { foo: string; num: number; bool: boolean } }',
].join('');

const TOP_LEVEL_KEYS = 7;
const NESTED_KEYS = 3;

// One `is<T>()` call is all the transformer needs: it rewrites the body into a
// straight-line boolean expression with no rule objects and no calls.
const inlined = transformTypeChecks(`export const aotIs = (d: unknown): boolean => is<${MODEL}>(d);\n`);

if (inlined.includes('is<')) {
  throw new Error(
    'zmdb-aot: the transformer left the is<T>() call in place, so this participant ' +
      'would benchmark an unresolved call rather than inlined output. Refusing to ' +
      'generate.',
  );
}

const generated = `// AUTO-GENERATED by src/generate.ts. Do not edit.
// Produced by @zmdb/aot-validator's transformTypeChecks over is<T>() source.
${inlined}
// Strict (the suite's \`equals\` contract) = structural check plus no excess keys.
// aotIs has already confirmed every declared key is present and well-typed, so
// "no excess keys" reduces to a key count. Counted with an early-exit for-in so
// there is no Object.keys allocation per call.
export function aotEquals(d: any): boolean {
  if (!aotIs(d)) return false;
  let top = 0;
  for (const _ in d) if (++top > ${TOP_LEVEL_KEYS}) return false;
  if (top !== ${TOP_LEVEL_KEYS}) return false;
  let nested = 0;
  for (const _ in d.deeplyNested) if (++nested > ${NESTED_KEYS}) return false;
  return nested === ${NESTED_KEYS};
}

// Matches the shipped parse<T> contract: validate, then return the input. For a
// purely structural type there is no coercion, so the validated value IS the
// parsed value — rebuilding it would measure an allocation the real API does not
// make.
export function aotParseSafe(d: any): any {
  if (!aotIs(d)) throw new Error('wrong type.');
  return d;
}

export function aotParseStrict(d: any): any {
  if (!aotEquals(d)) throw new Error('wrong type.');
  return d;
}
`;

const outFile = process.argv[2];
if (outFile === undefined) {
  throw new Error('zmdb-aot: usage: generate.cjs <output .ts path>');
}

writeFileSync(outFile, generated);
process.stdout.write(`zmdb-aot: generated from the real transform\n${inlined.trim()}\n`);
