// Derives everything the validation benchmark validates against from one type
// declaration (REQ-TF-9).
//
// Reads `harness/validation/aot-source.ts` — the four moltar cases written the way a user
// writes them, `is<Moltar>(data)` and friends — and writes two generated modules:
//
//   model.generated.ts  the IR the RUNTIME walker reads, from `Reflector.typeIR`
//   aot.generated.ts    the inlined functions, from the real `transformFile`
//
// Both come from the same call site, so the two rows in the results table are two paths
// over one declaration rather than two hand-written lookalikes. The AOT row in particular
// used to be a hand-inlined file whose comment claimed it was "exactly what the
// transformer would emit"; nobody could check that, and a benchmark nobody can check is a
// press release.
//
// It also transforms `shallow-source.ts` into `shallow.generated.ts` for the focused
// populated-row full-vs-depth-1 benchmark. That source carries both public calls, so the
// comparison likewise measures transformer output rather than hand-written validators.
//
// Usage:
//   node benchmarks/scripts/generate-validation-model.mjs           # write
//   node benchmarks/scripts/generate-validation-model.mjs --check   # fail on drift
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const VALIDATION = join(HERE, '..', 'harness', 'validation');
const PROJECT = join(VALIDATION, 'tsconfig.json');
const SOURCE = join(VALIDATION, 'aot-source.ts');
const SHALLOW_SOURCE = join(VALIDATION, 'shallow-source.ts');
const MODEL_OUT = join(VALIDATION, 'model.generated.ts');
const AOT_OUT = join(VALIDATION, 'aot.generated.ts');
const SHALLOW_OUT = join(VALIDATION, 'shallow.generated.ts');

const check = process.argv.includes('--check');

// The repository writes relative TypeScript imports with their emitted `.js` extension.
// Install its canonical resolver before loading any source module; static imports would be
// linked too early for the hook to affect their transitive dependencies.
await import('../../scripts/ts-specifier-hook.mjs');
const [{ findCallSites }, { Reflector }, { withSession }, { transformFile }] = await Promise.all([
  import('../../packages/compiler/src/reflect/callsites.js'),
  import('../../packages/compiler/src/reflect/index.js'),
  import('../../packages/compiler/src/reflect/session.js'),
  import('../../packages/compiler/src/transform/index.js'),
]);

const BANNER = from =>
  `// @generated by benchmarks/scripts/generate-validation-model.mjs from ${from}.\n// Do not edit: run \`yarn bench:validation:generate\`.\n`;

withSession({ project: PROJECT }, session => {
  // A type read out of a file that does not compile is a guess, and a validator generated
  // from a guess is worse than no validator.
  for (const file of [join(VALIDATION, 'model.ts'), SOURCE, SHALLOW_SOURCE]) {
    const diagnostics = session.diagnostics(file);
    if (diagnostics.length > 0) {
      throw new Error(`${file} has ${diagnostics.length} semantic diagnostic(s): ${JSON.stringify(diagnostics[0])}`);
    }
  }

  const sourceFile = session.sourceFile(SOURCE);
  if (!sourceFile) throw new Error(`${SOURCE} is not in ${PROJECT}`);

  // The IR comes off the same `is<Moltar>(...)` call site the transform reads, rather than
  // from a second lookup of the interface by name: one type, one reflection, and the two
  // generated modules cannot describe different shapes.
  const [site] = findCallSites(sourceFile, new Set(['is']));
  if (!site) throw new Error(`no is<T>() call site in ${SOURCE}`);
  const type = session.checker.getTypeFromTypeNode(site.typeArgument);
  if (!type) throw new Error('the checker gave no type for the is<T>() type argument');

  const reflector = new Reflector(session.checker, sourceFile, {});
  const ir = reflector.typeIR(type);
  if (reflector.diagnostics.length > 0) {
    throw new Error(`the reflection refused: ${JSON.stringify(reflector.diagnostics)}`);
  }

  const model = `${BANNER('harness/validation/model.ts')}
import type { TypeIR } from '../../../packages/schema-core/src/ir/index.js';

/** The runtime witness for \`Moltar\`: what the descriptor-walking path reads per call. */
export const MOLTAR: TypeIR = ${JSON.stringify(ir, null, 2)};
`;

  const result = transformFile(SOURCE, readFileSync(SOURCE, 'utf8'), { session });
  if (result.diagnostics.length > 0) {
    throw new Error(`the transform refused a site: ${JSON.stringify(result.diagnostics)}`);
  }
  if (!result.changed) throw new Error(`the transform left ${SOURCE} unchanged`);
  if (/\b(?:is|equals|validate)<Moltar>/.test(result.code)) {
    throw new Error('the transform left a generic call in place, so the AOT row would measure an unresolved call');
  }

  // Every call is inlined, so both imports are now unreferenced. Dropping them is what a
  // bundler does anyway — `@zmdb/aot-validator` is `sideEffects: false` — and it makes the
  // measured module honest about what the AOT path costs: nothing is loaded to run it.
  const aot = `${BANNER('harness/validation/aot-source.ts')}${strip(result.code, [
    /^import \{[^}]*\} from '[^']*utilities\/index\.[jt]s';\n/m,
    /^import type \{[^}]*\} from '[^']*';\n/m,
  ])}`;

  const shallowResult = transformFile(SHALLOW_SOURCE, readFileSync(SHALLOW_SOURCE, 'utf8'), { session });
  if (shallowResult.diagnostics.length > 0) {
    throw new Error(`the shallow transform refused a site: ${JSON.stringify(shallowResult.diagnostics)}`);
  }
  if (!shallowResult.changed) throw new Error(`the transform left ${SHALLOW_SOURCE} unchanged`);
  if (/\b(?:is|isShallow)<PopulatedOrderRow/.test(shallowResult.code)) {
    throw new Error('the transform left a populated-row generic call in place');
  }
  const shallow = `${BANNER('harness/validation/shallow-source.ts')}${strip(shallowResult.code, [
    /^import \{[^}]*\} from '[^']*utilities\/index\.[jt]s';\n/m,
  ])}`;

  function strip(code, patterns) {
    let out = code;
    for (const pattern of patterns) {
      if (!pattern.test(out)) throw new Error(`the transform output has no import matching ${String(pattern)}`);
      out = out.replace(pattern, '');
    }
    return out.replace(/\n{3,}/g, '\n\n');
  }

  let drifted = false;
  for (const [path, content] of [
    [MODEL_OUT, model],
    [AOT_OUT, aot],
    [SHALLOW_OUT, shallow],
  ]) {
    if (check) {
      const onDisk = readFileSync(path, 'utf8');
      if (onDisk !== content) {
        drifted = true;
        process.stdout.write(`drift: ${path} is not what the generator produces\n`);
      }
      continue;
    }
    writeFileSync(path, content);
    process.stdout.write(`wrote ${path}\n`);
  }

  if (drifted) {
    process.stdout.write('run `yarn bench:validation:generate` and commit the result\n');
    process.exitCode = 1;
  } else if (check) {
    process.stdout.write('the generated validation model is up to date\n');
  }
});
