// Generate the zmdb-aot validators for the moltar model by running the REAL
// transform (@zmdb/aot-validator plugin's transformTypeChecks) over is<T>()/
// assert<T>() source — so the benchmarked code is transformer-produced, not
// hand-written. Writes ./zmdb-aot-generated.mjs.
import { transformTypeChecks } from '../../../../packages/aot-validator/src/plugin/index.ts';
import { writeFileSync } from 'node:fs';

// The moltar data type, expressed as a TS type literal the transformer inlines.
const T = '{ number: number; negNumber: number; maxNumber: number; string: string; longString: string; boolean: boolean; deeplyNested: { foo: string; num: number; bool: boolean } }';

// is<T> and equals-equivalent (strict) source. The transformer turns each into
// a straight-line inline boolean expression.
const source = `
export const aotIs = (d: any): boolean => ${'is'}<${T}>(d);
`;
// Run the actual transform.
const inlinedIs = transformTypeChecks(source);

// For strict (equals), append an inline excess-key guard around the same inline
// check the transformer produced (strict = is + no-excess-keys; the transformer
// emits the structural check, the strict wrapper is generated here to match the
// equals<T> contract).
const TOP = ['number', 'negNumber', 'maxNumber', 'string', 'longString', 'boolean', 'deeplyNested'];
const NESTED = ['foo', 'num', 'bool'];

const generated = `// AUTO-GENERATED by gen-aot.mjs — do not edit. Produced by the real
// @zmdb/aot-validator transform over is<${'T'}>() source (transformer-produced,
// not hand-written).
${inlinedIs}
const TOP = ${JSON.stringify(TOP)};
const NESTED = ${JSON.stringify(NESTED)};
export function aotEquals(d: any): boolean {
  if (!aotIs(d)) return false;
  const kt = Object.keys(d); if (kt.length !== ${TOP.length}) return false;
  for (let i = 0; i < kt.length; i++) if (!TOP.includes(kt[i])) return false;
  const kn = Object.keys(d.deeplyNested); if (kn.length !== ${NESTED.length}) return false;
  for (let i = 0; i < kn.length; i++) if (!NESTED.includes(kn[i])) return false;
  return true;
}
export function aotParseSafe(d: any): any {
  if (!aotIs(d)) throw new Error('wrong type.');
  return { number: d.number, negNumber: d.negNumber, maxNumber: d.maxNumber, string: d.string, longString: d.longString, boolean: d.boolean, deeplyNested: { foo: d.deeplyNested.foo, num: d.deeplyNested.num, bool: d.deeplyNested.bool } };
}
export function aotParseStrict(d: any): any { if (!aotEquals(d)) throw new Error('wrong type.'); return d; }
`;

writeFileSync(new URL('./zmdb-aot-generated.ts', import.meta.url), generated);
console.log('generated zmdb-aot-generated.mjs from the real transform:');
console.log(inlinedIs.trim());
