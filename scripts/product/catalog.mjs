const PUBLISH_VERIFIER_REASON =
  'yarn verify:publish packs, installs, imports, and typechecks every public export from outside the repository.';

const freezeArray = values => Object.freeze([...values]);

function productPackage({ id, directory, npmName, role, facade, optionality, docsOwner, consumer }) {
  return Object.freeze({
    id,
    directory,
    npmName,
    role,
    facade: Object.freeze({
      root: freezeArray(facade.root),
      subpaths: freezeArray(facade.subpaths),
    }),
    optionality: Object.freeze({ ...optionality }),
    docsOwner,
    consumer: Object.freeze({ ...consumer }),
  });
}

